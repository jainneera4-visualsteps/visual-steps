import { access, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const registry = JSON.parse(await readFile(new URL('feature-registry.json', root), 'utf8'));

const screenshotPaths = new Set();
for (const feature of registry) {
  if (!feature.guideParagraphs?.length || !feature.screenshot?.src || !feature.screenshot?.alt || !feature.screenshot?.caption) {
    throw new Error(`${feature.id} must include article paragraphs and complete screenshot metadata`);
  }
  if (screenshotPaths.has(feature.screenshot.src)) throw new Error(`Feature screenshot is reused: ${feature.screenshot.src}`);
  screenshotPaths.add(feature.screenshot.src);
  if (!feature.screenshot.src.startsWith('/onboarding/')) throw new Error(`${feature.id} must use a captured application screenshot`);
  await access(new URL(`public${feature.screenshot.src}`, root));
}

const start = '<!-- FEATURE_REGISTRY:START -->';
const end = '<!-- FEATURE_REGISTRY:END -->';
const rows = registry.map((feature) => `| ${feature.title} | ${feature.plan} | ${feature.introducedOn} | ${feature.summary} |`).join('\n');
const generated = `${start}\n## Synchronized feature registry\n\nThis section is generated from \`feature-registry.json\`. Update the registry when a feature is added, changed, or removed; normal lint, test, development, and build commands refresh this table.\n\n| Feature | Plan | Introduced | Current description |\n| --- | --- | --- | --- |\n${rows}\n${end}`;

for (const filename of ['README.md', 'PRD.md']) {
  const url = new URL(filename, root);
  let content = await readFile(url, 'utf8');
  const expression = new RegExp(`${start}[\\s\\S]*?${end}`, 'm');
  content = expression.test(content) ? content.replace(expression, generated) : `${content.trimEnd()}\n\n${generated}\n`;
  await writeFile(url, content);
}

const serverUrl = new URL('server.ts', root);
const serverStart = '// FEATURE_REGISTRY_SERVER:START';
const serverEnd = '// FEATURE_REGISTRY_SERVER:END';
const serverRegistry = `${serverStart}\n// Generated by scripts/sync-feature-docs.mjs. Do not edit this block directly.\nconst productFeatureRegistry = ${JSON.stringify(registry, null, 2)} as const;\n${serverEnd}`;
let server = await readFile(serverUrl, 'utf8');
const serverExpression = new RegExp(`${serverStart}[\\s\\S]*?${serverEnd}`, 'm');
if (!serverExpression.test(server)) throw new Error('server.ts is missing feature registry generation markers');
server = server.replace(serverExpression, serverRegistry);
await writeFile(serverUrl, server);
